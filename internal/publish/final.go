package publish

// The generated-vs-human-edited final artifact pair (v0.7, issue #146).
//
// After a run completes, a human edits the generated output (the rendered
// article or thread) in the workspace. This file is the explicit persistence
// path for that edit: it copies the generated output into the run directory
// verbatim, persists the human's final file beside it, baselines both by
// content digest, and records the pair on the manifest's final_state summary.
//
// Core rules:
//
//   - The generated artifact is NEVER overwritten or rewritten: the run
//     directory copy is read-only provenance, and the final version lives in
//     its own document.
//   - Nothing is inferred from publication state: the pair is recorded only
//     through RecordFinal (an explicit user action), and the publication
//     result is an optional reference that travels with the explicit call.
//   - The run must be READY (run succeeded, final check passed, review
//     bundle ready) — the same gate publication requires.
//   - Both content files cross the workspace sanitization boundary exactly
//     like every other run file; the recorded digests hash the bytes that
//     actually land on disk (after redaction), so the record always matches
//     what is stored.
//   - A corrupted or tampered persisted document fails closed, and digest
//     drift of an existing record is surfaced, never silently rewritten.

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"github.com/Mundo-Dolphins/local-newsroom/internal/review"
	"github.com/Mundo-Dolphins/local-newsroom/internal/run"
)

// RecordFinalRequest requests the persistence of one generated-vs-final
// artifact pair for a run.
type RecordFinalRequest struct {
	// FinalPath is the path (run-relative or absolute) of the human-edited
	// final artifact (required).
	FinalPath string

	// Editor identifies the human who produced the final version (required;
	// redacted on record).
	Editor string

	// PublishedURI is the optional external reference of the publication
	// result, when known (e.g. the published page or post URL).
	PublishedURI string

	// EditedAt is when the final version was recorded; defaults to now.
	EditedAt time.Time
}

// RecordFinalResult is the durable record of a recorded pair.
type RecordFinalResult struct {
	// Name is the persisted file base name (shared by both documents).
	Name string

	// GeneratedPath is the run-relative path of the generated copy.
	GeneratedPath string

	// GeneratedHash is the digest of the persisted generated bytes.
	GeneratedHash string

	// FinalPath is the run-relative path of the final version.
	FinalPath string

	// FinalHash is the digest of the persisted final bytes.
	FinalHash string

	// ManifestPath is the absolute path of the updated manifest.
	ManifestPath string
}

// ErrFinalNotCompleted indicates that the run has no recordable output: it
// did not reach a terminal state, its render stage did not succeed, it is
// not READY for publication, or its rendered output is missing.
var ErrFinalNotCompleted = errors.New("run is not completed or not ready")

// ErrFinalUnreadable indicates that a persisted final document that was
// expected to exist cannot be read back (the run directory is unreadable or
// was raced away).
var ErrFinalUnreadable = errors.New("final artifact unreadable")

// digestOfBytes returns the canonical "sha256:<64 hex>" digest of data.
func digestOfBytes(data []byte) string {
	sum := sha256.Sum256(data)
	return "sha256:" + hex.EncodeToString(sum[:])
}

// finalNameRe allows conservative final artifact file names. The name is
// user-visible in the run directory tree, so it uses the same character set
// as run and plan IDs: letters, digits, dot, dash, underscore.
var finalNameRe = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9._-]{0,127}$`)

// finalExtensionRe allows the rendered output extensions (article markdown,
// thread text).
var finalExtensionRe = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9+-]{0,15}$`)

// finalBaseName derives the file base name of the final documents from the
// generated artifact path.
func finalBaseName(genRel string) (string, error) {
	base := path.Base(genRel)
	ext := path.Ext(base)
	name := strings.TrimSuffix(base, ext)
	if !finalNameRe.MatchString(name) {
		return "", fmt.Errorf("final artifact name %q is not a safe file name: use letters, digits, '.', '-', '_' (1-128 chars)", name)
	}
	if ext != "" && !finalExtensionRe.MatchString(strings.TrimPrefix(ext, ".")) {
		return "", fmt.Errorf("final artifact extension %q is not a safe file extension: use letters, digits, '+' or '-' (1-16 chars)", ext)
	}
	return name, nil
}

// generatedPathOfRun returns the run-relative path of the generated output
// whose final version has been recorded.
//
// The pair is baselined by content digest, not by name, so the source of
// the generated copy is derived from the run's rendered outputs: an article
// (output/article.md) is preferred when present — it is the canonical
// long-form output of both article and hybrid runs — and the first rendered
// file (the thread in a thread run) otherwise. The user passes the final
// file to match: the same output kind the run rendered.
func generatedPathOfRun(m *run.Manifest, runDir string) (string, error) {
	var genPath string
	for _, a := range m.Artifacts {
		if a.Kind != run.ArtifactKindRendered || a.Path == "" {
			continue
		}
		if _, err := os.Stat(filepath.Join(runDir, filepath.FromSlash(a.Path))); err == nil {
			if strings.HasSuffix(a.Path, ".md") {
				// The article is the canonical long-form output: it wins
				// when the run renders both (hybrid).
				genPath = a.Path
				break
			}
			genPath = a.Path // first/last rendered file (a thread run renders one)
		}
	}
	if genPath == "" {
		return "", fmt.Errorf("%w: run %s has no rendered output to pair a final artifact with (the render stage produced nothing persistable)", ErrFinalNotCompleted, m.ID)
	}
	return genPath, nil
}

// recordFinalDocument persists one final pair document through the store
// (sanitization boundary, atomic write) and returns the digest of the bytes
// that actually landed on disk.
func (e *Engine) recordFinalDocument(m *run.Manifest, rel string, ref run.ArtifactRef, data []byte) (string, error) {
	if _, err := e.store.SaveArtifact(m.ID, ref, data); err != nil {
		return "", fmt.Errorf("persisting %s: %w", rel, err)
	}
	persisted, err := e.store.LoadArtifact(m.ID, rel)
	if err != nil {
		return "", fmt.Errorf("%w: %s was written but cannot be read back: %v", ErrFinalUnreadable, rel, err)
	}
	return digestOfBytes(persisted), nil
}

// verifyFinalDocuments fails closed on any persisted final document that
// cannot be read back (the directory was raced away or is unreadable).
// Final calls it before re-hashing each recorded document so an unreadable
// state is reported as ErrFinalUnreadable rather than a bare I/O error.
func (e *Engine) verifyFinalDocuments(m *run.Manifest, rels ...string) error {
	for _, rel := range rels {
		if _, err := e.store.LoadArtifact(m.ID, rel); err != nil {
			return fmt.Errorf("%w: %s: %v", ErrFinalUnreadable, rel, err)
		}
	}
	return nil
}

// RecordFinal persists the generated vs human-edited final artifact pair of
// a completed run (v0.7, issue #146).
//
// It is fail-closed end to end:
//
//   - the run must be terminal and the review bundle must report readiness
//     (run succeeded, final factual check passed) — the same verdict
//     publication requires, evaluated against the generated output bytes;
//   - the generated copy is persisted verbatim into final/generated/ and is
//     never written to again (originals preserved, both versions kept);
//   - both content documents cross the store's sanitization boundary and
//     are refused (ErrSanitization) rather than persisted dirty;
//   - the digests are computed from the persisted bytes, so the record
//     always matches what is stored.
//
// The pair replaces any previously recorded final state (re-editing
// replaces the record; re-recording the identical pair is a no-op) and
// advances the manifest's updated_at, which a resumed or re-saved manifest
// may not regress to.
func (e *Engine) RecordFinal(ctx context.Context, runID run.RunID, req RecordFinalRequest, bundle *review.Bundle) (*RecordFinalResult, error) {
	m, dir, err := e.store.LoadManifest(runID)
	if err != nil {
		return nil, fmt.Errorf("loading manifest for run %s: %w", runID, err)
	}
	if m.ID != runID {
		return nil, fmt.Errorf("run ID mismatch: the manifest of %s is for %s", runID, m.ID)
	}

	if !m.Status.Terminal() {
		return nil, fmt.Errorf("%w: run %s is %s; a final artifact pair can only be recorded for a completed run", ErrFinalNotCompleted, m.ID, m.Status)
	}

	// The rendered output is resolved through the same path the render
	// stage and the publish flow use: the rendered artifact reference whose
	// file exists (an article when both exist in a hybrid run).
	genRel, err := generatedPathOfRun(m, dir)
	if err != nil {
		return nil, err
	}
	genContent, err := e.loadContent(m.ID, genRel)
	if err != nil {
		return nil, fmt.Errorf("%w: %v", ErrFinalNotCompleted, err)
	}

	// The same readiness verdict publication requires, evaluated against
	// the generated output bytes (a pair may only be recorded for output
	// that is ready to use).
	gate := BuildGateEvidence(m, bundle, genContent, e.now())
	if ok, why := GateReady(gate); !ok {
		return nil, fmt.Errorf("%w: the run is not READY for publication: %s", ErrFinalNotCompleted, why)
	}

	if strings.TrimSpace(req.Editor) == "" {
		return nil, fmt.Errorf("an editor identifier is required: the final version must be attributed to an explicit human")
	}
	if strings.TrimSpace(req.FinalPath) == "" {
		return nil, fmt.Errorf("a final artifact path is required: point at the human-edited file")
	}
	finalAbs := req.FinalPath
	if !filepath.IsAbs(finalAbs) {
		finalAbs = filepath.Join(dir, filepath.FromSlash(finalAbs))
	}
	finalAbs = filepath.Clean(finalAbs)

	finalData, err := os.ReadFile(finalAbs)
	if err != nil {
		return nil, fmt.Errorf("reading the final artifact %s: %w", finalAbs, err)
	}

	at := req.EditedAt
	if at.IsZero() {
		at = e.now()
	}

	name, err := finalBaseName(genRel)
	if err != nil {
		return nil, fmt.Errorf("deriving the final artifact name from %s: %w", genRel, err)
	}
	genPath := run.FinalGeneratedDir + "/" + name + path.Ext(genRel)
	finalPath := run.FinalArtifactsDir + "/" + name + path.Ext(genRel)

	genRef := run.ArtifactRef{
		Kind:       run.ArtifactKindRendered,
		ID:         "final-generated-" + name,
		Stage:      "",
		Path:       genPath,
		ProducedAt: run.NewTimestamp(at),
	}
	finalRef := run.ArtifactRef{
		Kind:       run.ArtifactKindRendered,
		ID:         "final-" + name,
		Stage:      "",
		Path:       finalPath,
		ProducedAt: run.NewTimestamp(at),
	}

	// Persist the generated copy first (originals preserved), then the
	// final version; both through the sanitization boundary, both fail
	// closed when a secret cannot be removed.
	genHash, err := e.recordFinalDocument(m, genPath, genRef, genContent)
	if err != nil {
		return nil, err
	}
	finalHash, err := e.recordFinalDocument(m, finalPath, finalRef, finalData)
	if err != nil {
		return nil, err
	}

	fs := &run.FinalState{
		GeneratedPath: genPath,
		GeneratedHash: genHash,
		FinalPath:     finalPath,
		FinalHash:     finalHash,
		Editor:        run.RedactSecrets(req.Editor),
		EditedAt:      run.NewTimestamp(at),
	}
	if uri := strings.TrimSpace(req.PublishedURI); uri != "" {
		fs.PublishedURI = run.RedactSecrets(uri)
	}
	if err := m.RecordFinalState(fs, at); err != nil {
		return nil, fmt.Errorf("recording the final state on manifest %s: %w", m.ID, err)
	}
	manifestPath, err := e.store.SaveManifest(m)
	if err != nil {
		return nil, fmt.Errorf("persisting manifest %s (final state): %w", m.ID, err)
	}
	return &RecordFinalResult{
		Name:          name,
		GeneratedPath: genPath,
		GeneratedHash: genHash,
		FinalPath:     finalPath,
		FinalHash:     finalHash,
		ManifestPath:  manifestPath,
	}, nil
}

// FinalReport is the inspection projection of a run's recorded final state:
// the recorded pair plus the current digest of both documents, so a
// tampered or drifted document is surfaced instead of trusted.
type FinalReport struct {
	// Recorded is the manifest's final_state summary (nil when the run has
	// no recorded final state).
	Recorded *run.FinalState `json:"recorded,omitempty"`

	// GeneratedHashNow is the current digest of the persisted generated
	// document (only meaningful when Recorded is set).
	GeneratedHashNow string `json:"generated_hash_now,omitempty"`

	// FinalHashNow is the current digest of the persisted final document
	// (only meaningful when Recorded is set).
	FinalHashNow string `json:"final_hash_now,omitempty"`

	// GeneratedDrifts reports that the generated document no longer matches
	// the recorded digest (it was modified after the record).
	GeneratedDrifts bool `json:"generated_drifts"`

	// FinalDrifts reports that the final document no longer matches the
	// recorded digest (it was modified after the record).
	FinalDrifts bool `json:"final_drifts"`
}

// Final inspects the run's recorded final state (v0.7, issue #146).
//
// It never mutates anything. A run without a recorded final state returns a
// nil Recorded (not an error). A documented file that cannot be read fails
// closed (ErrFinalUnreadable); a document whose bytes no longer digest to
// the recorded value is reported through the drift flags — a tampered
// record is never silently trusted.
func (e *Engine) Final(ctx context.Context, runID run.RunID) (*FinalReport, error) {
	m, _, err := e.store.LoadManifest(runID)
	if err != nil {
		return nil, fmt.Errorf("loading manifest for run %s: %w", runID, err)
	}
	if m.FinalState == nil {
		return &FinalReport{}, nil
	}
	rep := &FinalReport{Recorded: m.FinalState}
	for _, pair := range []struct {
		kind  string
		rel   string
		field *string
	}{
		{"generated", m.FinalState.GeneratedPath, &rep.GeneratedHashNow},
		{"final", m.FinalState.FinalPath, &rep.FinalHashNow},
	} {
		if err := e.verifyFinalDocuments(m, pair.rel); err != nil {
			return nil, err
		}
		data, err := e.store.LoadArtifact(m.ID, pair.rel)
		if err != nil {
			return nil, fmt.Errorf("%w: %s: %v", ErrFinalUnreadable, pair.rel, err)
		}
		_ = pair.kind
		*pair.field = digestOfBytes(data)
	}
	rep.GeneratedDrifts = rep.GeneratedHashNow != m.FinalState.GeneratedHash
	rep.FinalDrifts = rep.FinalHashNow != m.FinalState.FinalHash
	return rep, nil
}
